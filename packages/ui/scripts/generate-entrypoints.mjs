import { readdir, readFile, writeFile } from "node:fs/promises"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const packageDir = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const uiDir = resolve(packageDir, "src/components/ui")
const catalogPath = resolve(packageDir, "../catalog/src/entities.ts")
const generatedHeader = "// Generated by packages/ui/scripts/generate-entrypoints.mjs. Do not edit.\n"

const files = (await readdir(uiDir))
  .filter((file) => file.endsWith(".tsx") && file !== "icon.tsx")
  .sort()
const modules = files.map((file) => file.slice(0, -4))

await writeFile(
  resolve(packageDir, "src/index.ts"),
  `${generatedHeader}${modules.map((module) => `export * from "./components/ui/${module}"`).join("\n")}\n`,
)
await writeFile(resolve(packageDir, "src/marks.ts"), `${generatedHeader}export * from "./components/ui/marks/index"\n`)
await writeFile(resolve(packageDir, "src/icon.ts"), `${generatedHeader}export * from "./components/ui/icon"\n`)
await writeFile(resolve(packageDir, "src/utils.ts"), `${generatedHeader}export * from "./lib/utils"\n`)

const catalogSource = await readFile(catalogPath, "utf8")
const catalogSources = new Set(
  [...catalogSource.matchAll(/"(?:kernel-portal\/src\/components\/ui|packages\/ui\/src\/components\/ui)\/([^"/]+)\.tsx"/g)]
    .map((match) => match[1]),
)
const api = modules.map((module) => ({ module, catalogBacked: catalogSources.has(module) }))
await writeFile(resolve(packageDir, "api.json"), `${JSON.stringify({ entry: ".", modules: api }, null, 2)}\n`)
