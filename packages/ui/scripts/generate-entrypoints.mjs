import { readdir, readFile, writeFile } from "node:fs/promises"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const packageDir = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const repoRoot = resolve(packageDir, "../..")
const uiDir = resolve(repoRoot, "kernel-portal/src/components/ui")
const catalogPath = resolve(repoRoot, "packages/catalog/src/entities.ts")
const generatedHeader = "// Generated by packages/ui/scripts/generate-entrypoints.mjs. Do not edit.\n"

const files = (await readdir(uiDir))
  .filter((file) => file.endsWith(".tsx") && file !== "icon.tsx")
  .sort()
const exports = files.map((file) => `export * from "../../../kernel-portal/src/components/ui/${file.slice(0, -4)}"`)
await writeFile(resolve(packageDir, "src/index.ts"), `${generatedHeader}${exports.join("\n")}\n`)

const catalogSource = await readFile(catalogPath, "utf8")
const catalogSources = new Set(
  [...catalogSource.matchAll(/"kernel-portal\/src\/components\/ui\/([^"/]+)\.tsx"/g)].map((match) => match[1]),
)
const api = files.map((file) => {
  const module = file.slice(0, -4)
  return { module, catalogBacked: catalogSources.has(module) }
})
await writeFile(resolve(packageDir, "api.json"), `${JSON.stringify({ entry: ".", modules: api }, null, 2)}\n`)
