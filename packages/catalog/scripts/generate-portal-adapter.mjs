import { readFile, writeFile } from "node:fs/promises"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const repoRoot = resolve(packageRoot, "../..")
const outputFile = resolve(repoRoot, "kernel-portal/src/lib/component-meta.generated.ts")
const checkOnly = process.argv.includes("--check")

// entities.ts is generated from the per-entity JSON store; refresh it first so
// direct edits to packages/catalog/src/entities/*.json flow through generation.
const store = await import(`file://${resolve(repoRoot, "scripts/ds/lib/catalog-file.mjs").replaceAll("\\", "/")}`)
const entitiesFile = resolve(packageRoot, "src/entities.ts")
if (!checkOnly && store.hasCatalogStore(entitiesFile)) {
  const parsed = store.parseCatalogFile(entitiesFile)
  const regenerated = store.generateEntitiesSource(parsed, store.readCatalogStore(store.catalogStoreDir(entitiesFile)))
  if (regenerated !== store.serializeCatalogFile(parsed)) {
    await writeFile(entitiesFile, regenerated)
    console.log("Regenerated packages/catalog/src/entities.ts from entities/*.json")
  }
}

const output = `/* Generated by packages/catalog/scripts/generate-portal-adapter.mjs. Do not edit directly. */
import { catalog, selectPortalLifecycleMeta } from "@kernel/catalog"

export const componentMeta = selectPortalLifecycleMeta(catalog)
export const components = componentMeta.filter((entity) => entity.group === "component")
`

if (checkOnly) {
  const tracked = await readFile(outputFile, "utf8").catch(() => "")
  // Normalize CRLF so checkouts with core.autocrlf=true compare identically.
  if (tracked.replaceAll("\r\n", "\n") !== output) {
    console.error("CATALOG generated-stale: portal lifecycle adapter is stale; run npm run catalog:generate")
    process.exit(1)
  }
  console.log("CATALOG-GENERATED-OK: portal lifecycle adapter is current")
} else {
  await writeFile(outputFile, output)
  console.log("Generated kernel-portal/src/lib/component-meta.generated.ts")
}
