/* Sell-side routes from every buying point to its nearest destinations.
   `sell-routes.json` is generated by scripts/build-sell-routes.mjs over the FRA
   main-line rail network and the barge-river network — regenerate there, not here.
   Rail and barge paths are shortest-track guesses (object.route), never contracts. */
import raw from "./sell-routes.json"
import type { SellRoute, SellRoutes } from "@app/map/model"

type Raw = {
  segs: [number, number][][]
  sites: Record<string, { k: SellRoute["kind"]; d: number; m: SellRoute["mode"]; mi: number; s?: number[] }[]>
}

const data = raw as unknown as Raw

export const SELL_ROUTES: SellRoutes = {
  segments: data.segs,
  bySite: new Map(
    Object.entries(data.sites).map(([id, list]) => [
      Number(id),
      list.map((r) => ({ kind: r.k, destId: r.d, mode: r.m, miles: r.mi, segs: r.s })),
    ]),
  ),
}
